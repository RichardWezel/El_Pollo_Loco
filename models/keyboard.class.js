/**
 * Simple container for keyboard state flags. Instances are used by the
 * input handling code to track which keys or buttons are currently active.
 */
class Keyboard {

    LEFT = false;
    RIGHT = false;
    UP = false;
    DOWN = false;
    SPACE = false;
    ENTER = false;
    KeyD = false;
    KeyM = false;
    KeyF = false;
    KeyH = false;
    KeyP = false;
}